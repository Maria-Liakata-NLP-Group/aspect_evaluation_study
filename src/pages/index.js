import { useState } from "react";
import Head from "next/head";
import AnnotationPanel from "./annotation";
import Intro from "./intro";
import Image from "next/image";
import localFont from "next/font/local";

import data from "../data/clfever.json";

const geistSans = localFont({
  src: "./fonts/GeistVF.woff",
  variable: "--font-geist-sans",
  weight: "100 900",
});
const geistMono = localFont({
  src: "./fonts/GeistMonoVF.woff",
  variable: "--font-geist-mono",
  weight: "100 900",
});

export default function Home() {
  const [stage, setStage] = useState("intro"); // intro, annotation or finish
  const [claim, setClaim] = useState(0);

  // Function to get the next claim
  const getNextClaim = () => {
    if (claim < data.length - 1) {
      setClaim(claim + 1);
    } else {
      setStage("finish");
    }
  };

  const getStagePage = () => {
    if (stage === "intro") {
      return <Intro nextButtonFunction={() => setStage("annotation")} />
    }
    else if (stage === "annotation") {
      return (
        <AnnotationPanel
          claim={data[claim].claim}
          evidence={data[claim].evidence}
          veracity={data[claim].label}
          nextButtonFunction={getNextClaim}
        />
      );
    } else if (stage === "finish") {
      return (
        <div className="section">
          <h1 className="title">Thank you for annotating the data!</h1>
        </div>
      );
    }
  }

  return (
    <>
      <Head>
        <title>NLP data annotation</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <main>
        {getStagePage()}
      </main>
    </>
  );
}
